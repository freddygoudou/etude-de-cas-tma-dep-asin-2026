DROP TABLE IF EXISTS inscriptions;
DROP TABLE IF EXISTS candidats;
DROP TABLE IF EXISTS centres;
DROP TABLE IF EXISTS concours;

CREATE TABLE concours (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(10) NOT NULL UNIQUE,
  libelle VARCHAR(100) NOT NULL,
  date_epreuve DATE NOT NULL,
  cloture TIMESTAMP NOT NULL
);

CREATE TABLE centres (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(1) NOT NULL UNIQUE,
  nom VARCHAR(50) NOT NULL,
  capacite INTEGER NOT NULL
);

CREATE TABLE candidats (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  npi VARCHAR(10) NOT NULL,
  nom VARCHAR(60) NOT NULL,
  prenoms VARCHAR(80) NOT NULL,
  date_naissance DATE NOT NULL,
  cree_le TIMESTAMP NOT NULL,
  CONSTRAINT uq_candidats_npi UNIQUE (npi)
);

CREATE TABLE inscriptions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  concours_id BIGINT NOT NULL REFERENCES concours (id),
  centre_id BIGINT NOT NULL REFERENCES centres (id),
  npi VARCHAR(10) NOT NULL,
  numero_table VARCHAR(6) NOT NULL,
  statut VARCHAR(30) NOT NULL,
  date_epreuve DATE NOT NULL,
  cree_le TIMESTAMP NOT NULL,
  CONSTRAINT uq_inscriptions_centre_numero UNIQUE (centre_id, numero_table),
  CONSTRAINT uq_inscriptions_npi_concours UNIQUE (npi, concours_id),
  CONSTRAINT uq_inscriptions_npi_jour UNIQUE (npi, date_epreuve)
);
CREATE INDEX ix_inscriptions_centre_concours ON inscriptions (centre_id, concours_id);

